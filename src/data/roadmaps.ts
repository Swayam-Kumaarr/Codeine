// ─────────────────────────────────────────────────────────────────────────────
// Helper: given a start date string (ISO), return current day number (1-based)
// ─────────────────────────────────────────────────────────────────────────────
export function getDayNumber(startDateISO: string, daysPaused = 0): number {
  const start = new Date(startDateISO)
  start.setHours(0, 0, 0, 0)
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  const diff = Math.floor((today.getTime() - start.getTime()) / 86_400_000)
  return Math.max(1, diff + 1 - daysPaused)
}

// ─────────────────────────────────────────────────────────────────────────────
// Helper: given day number, return current topic + day within topic
// ─────────────────────────────────────────────────────────────────────────────
export function getCurrentTopic(roadmap: Roadmap, dayNumber: number) {
  const clamped = Math.min(dayNumber, roadmap.totalDays)
  const topic = roadmap.topics.find(t => clamped >= t.startDay && clamped <= t.endDay)
    ?? roadmap.topics[roadmap.topics.length - 1]
  const dayWithinTopic = clamped - topic.startDay + 1
  return { topic, dayWithinTopic }
}
